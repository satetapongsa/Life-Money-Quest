// Bundle server/og-card.jsx (JSX + React) เป็นไฟล์ Node ล้วนที่ api/og.js import ได้: npm run build:og
// ผลลัพธ์ api/_gen/og-card.js ถูก commit ไว้ด้วย เพื่อให้ฟังก์ชันบน Vercel ใช้ได้โดยไม่ต้องพึ่งลำดับการ build
import { build } from 'vite'
import react from '@vitejs/plugin-react'

await build({
  configFile: false,
  logLevel: 'warn',
  plugins: [react()],
  define: { 'process.env.NODE_ENV': '"production"' },
  ssr: { noExternal: true },
  build: {
    ssr: 'server/og-card.jsx',
    outDir: 'api/_gen',
    emptyOutDir: true,
    minify: true,
    rollupOptions: { output: { format: 'es', entryFileNames: 'og-card.js', banner: '// GENERATED by scripts/build-og.mjs from server/og-card.jsx — do not edit' } },
  },
})
console.log('built api/_gen/og-card.js')
