// อัตราเงินเฟ้อทั่วไปของไทยโดยประมาณ (% ต่อปี) — ใช้เพื่อความสนุก ไม่ใช่ตัวเลขทางการ
// ปีที่ไม่มีในตารางใช้ค่าเฉลี่ยของยุคนั้นแทน
const RATE = {
  1980: 19.7, 1981: 12.7, 1982: 5.2, 1983: 3.8, 1984: 0.9, 1985: 2.4, 1986: 1.8, 1987: 2.5, 1988: 3.9, 1989: 5.4,
  1990: 5.9, 1991: 5.7, 1992: 4.1, 1993: 3.4, 1994: 5.1, 1995: 5.8, 1996: 5.9, 1997: 5.6, 1998: 8.1, 1999: 0.3,
  2000: 1.6, 2001: 1.6, 2002: 0.7, 2003: 1.8, 2004: 2.8, 2005: 4.5, 2006: 4.6, 2007: 2.2, 2008: 5.5, 2009: -0.9,
  2010: 3.3, 2011: 3.8, 2012: 3.0, 2013: 2.2, 2014: 1.9, 2015: -0.9, 2016: 0.2, 2017: 0.7, 2018: 1.1, 2019: 0.7,
  2020: -0.8, 2021: 1.2, 2022: 6.1, 2023: 1.2, 2024: 0.4, 2025: 0.0,
}

export function inflationRate(year) {
  if (RATE[year] !== undefined) return RATE[year]
  if (year < 1960) return 3
  if (year < 1970) return 2.5
  if (year < 1980) return 8
  return 1 // อนาคต/ปีปัจจุบันที่ยังไม่มีข้อมูล
}

// เงิน 1 บาทในปี fromYear มีค่าเท่ากับกี่บาทในปี toYear
export function inflationFactor(fromYear, toYear) {
  let f = 1
  for (let y = fromYear + 1; y <= toYear; y++) f *= 1 + inflationRate(y) / 100
  return f
}
